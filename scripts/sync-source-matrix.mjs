import fs from "node:fs";
import path from "node:path";
import { data, root } from "./load-data.mjs";

const args = new Set(process.argv.slice(2));
const outputPath = path.join(root, "docs", "audits", "model-source-coverage.md");
const sourcesById = new Map(data.sources.map((source) => [source.id, source]));
const auditsBySourceId = new Map((data.sourceAudits || []).map((audit) => [audit.sourceId, audit]));
const familyByBenchmarkId = new Map();
for (const family of data.benchmarkFamilies || []) {
  for (const variant of family.variants) familyByBenchmarkId.set(variant.benchmarkId, family.id);
}

const escapeCell = (value) => String(value ?? "").replaceAll("|", "\\|").replaceAll("\n", " ");
const modelReferenceIds = (model) => [...new Set([model.sourceId, ...(model.referenceSourceIds || [])].filter(Boolean))];
const modelFamilyCount = (modelId) => new Set(data.observations
  .filter((observation) => observation.modelId === modelId)
  .map((observation) => familyByBenchmarkId.get(observation.benchmarkId) || observation.benchmarkId)).size;
const targetModels = (audit) => audit?.targetModels || (audit?.targetModelId ? [{ modelId: audit.targetModelId }] : []);
const auditCoversModel = (audit, modelId) => {
  if (!audit) return false;
  if (audit.status === "complete") return true;
  if (audit.status !== "target-complete") return false;
  return targetModels(audit).some((target) => target.modelId === modelId);
};
const officialReferences = (model) => modelReferenceIds(model)
  .map((sourceId) => sourcesById.get(sourceId))
  .filter((source) => source && source.kind !== "benchmark" && source.vendorId === model.vendorId);
const auditState = (model, references) => {
  if (!references.length) return "Missing first-party source";
  const audits = references.map((source) => auditsBySourceId.get(source.id)).filter(Boolean);
  if (audits.some((audit) => auditCoversModel(audit, model.id))) return "Target/full result scope checked";
  if (audits.some((audit) => audit.status === "partial")) return "Partial";
  if (audits.some((audit) => audit.status === "metadata-only")) return "Metadata only";
  return "Pending";
};
const sourceLinks = (references) => references.length
  ? references.map((source) => {
      const audit = auditsBySourceId.get(source.id);
      const status = audit?.status || "missing audit";
      return `[${escapeCell(source.title)}](${source.url}) (${status})`;
    }).join("<br>")
  : "—";

const sections = [
  {
    title: "Curated model releases",
    description: "Models intended to have direct first-party benchmark coverage. Base-model entries remain separate from served multimodal or agent products.",
    models: data.models.filter((model) => !["comparison-only", "metadata-only", "pending"].includes(model.scoreStatus))
  },
  {
    title: "Comparison-only models",
    description: "Models currently supported only by another provider's table or an official benchmark leaderboard. These rows are useful comparisons, but they remain explicitly incomplete until a first-party release surface is audited.",
    models: data.models.filter((model) => model.scoreStatus === "comparison-only")
  },
  {
    title: "Metadata-only and pending releases",
    description: "Known exact releases with no publishable score column yet, or releases whose score mapping is still unresolved.",
    models: data.models.filter((model) => ["metadata-only", "pending"].includes(model.scoreStatus))
  }
];

const allRows = data.models.map((model) => {
  const references = officialReferences(model);
  return { model, references, auditState: auditState(model, references) };
});
const checkedCount = allRows.filter((row) => row.auditState === "Target/full result scope checked").length;
const firstPartyCount = allRows.filter((row) => row.references.length > 0).length;

const lines = [
  "# Model source coverage",
  "",
  `Generated from the dataset on ${data.meta.updated}. Do not edit this file by hand; run \`npm run sync-source-matrix\`.`,
  "",
  "This matrix makes source-surface gaps visible. A score can enter BenchBoard from another provider's comparison table or an official benchmark leaderboard, but that does not mean the model's own release page, model card, repository, or technical/system report has been checked.",
  "",
  `- ${data.models.length} model records`,
  `- ${firstPartyCount} records linked to at least one first-party model source`,
  `- ${checkedCount} records with a completed full-source or target-column result audit`,
  `- ${data.sources.length} primary sources in the registry`,
  "",
  "Audit states describe the linked source scope, not independent reproduction. `target-complete` means every public numeric cell for the named model column in that scope was checked; comparison columns may still be incomplete. `complete` means the declared public result-table scope was checked. `metadata-only` means the surface contains no independent score table.",
  ""
];

for (const section of sections) {
  lines.push(`## ${section.title}`, "", section.description, "", "| Model | Provider | Recorded families | Source audit | First-party surfaces |", "| --- | --- | ---: | --- | --- |");
  for (const model of [...section.models].sort((a, b) => a.vendor.localeCompare(b.vendor) || a.name.localeCompare(b.name))) {
    const references = officialReferences(model);
    lines.push(`| ${escapeCell(model.name)} | ${escapeCell(model.vendor)} | ${modelFamilyCount(model.id)} | ${auditState(model, references)} | ${sourceLinks(references)} |`);
  }
  lines.push("");
}

const output = `${lines.join("\n").trim()}\n`;
if (args.has("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== output) {
    console.error("docs/audits/model-source-coverage.md is out of date; run npm run sync-source-matrix");
    process.exit(1);
  }
  console.log("source matrix is current");
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`updated ${path.relative(root, outputPath)}`);
}
